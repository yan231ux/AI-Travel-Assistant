package com.yuntu.tripplanner.common;

/**
 * 管理端权限点（设计方案 §11 第五阶段：角色和权限细化）。
 *
 * <p><b>为什么用权限点而不是直接判角色</b>：如果每个接口写"必须等于某个角色名"，
 * 新增角色就要满仓库改判断；权限点把"能做什么"与"谁拥有它"解耦——
 * 角色到权限的映射只在 {@link AdminRole} 里声明一次，接口只声明"我需要哪个权限点"。
 *
 * <p><b>为什么一个业务域一个权限点</b>：粒度太细（增/删/改各一个）会让矩阵爆炸且难维护；
 * 粒度太粗（只有一个 ADMIN）就回到原点。这里按<b>业务域</b>切，与左侧导航一一对应，
 * 答辩时可以逐个念"这个角色能进哪几个菜单"。
 */
public enum AdminPermission {

    /** 内容审核：帖子审核（AI 初筛结果人工决策）、举报处理、帖子治理 */
    CONTENT_REVIEW("内容审核"),

    /** 攻略与城市内容：攻略新增/编辑/审核/发布/下线、城市专题内容 */
    GUIDE_MANAGE("攻略与城市内容"),

    /** 推荐运营：A/B 实验、人工干预（置顶/降权/黑名单/城市精选）、城市推荐质量 */
    RECOMMEND_OPS("推荐运营"),

    /** 数据看板：六张统计图与运营读数。只读、无破坏性，因此对所有管理端角色开放 */
    ANALYTICS_VIEW("数据看板"),

    /** 景点数据治理：人工修正与字段锁定、下线、合并重复景点 */
    SPOT_GOVERN("景点数据治理"),

    /** 用户与账号治理：限制发帖/暂停评论/暂停账号/分配角色 */
    USER_GOVERN("用户与账号治理"),

    /** 全链路审计日志查询（谁在什么时候做了什么） */
    AUDIT_VIEW("审计日志");

    private final String label;

    AdminPermission(String label) {
        this.label = label;
    }

    /** 中文名（管理端展示，避免前端再维护一份翻译表） */
    public String label() {
        return label;
    }
}
